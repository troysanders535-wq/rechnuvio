/**
 * Generate docs/TOOL-AUDIT-SUMMARY.md from the audit evidence.
 *
 * The document is written from the evidence files rather than by hand, so it
 * can never drift away from the measurements.
 *
 * Usage: node scripts/audit/build-audit-summary.mjs
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { TOOLS_CATALOG } from "../../src/data/tools.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const docsDir = join(root, "docs");
const evidenceDir = join(docsDir, "audit-evidence");
const outPath = join(docsDir, "TOOL-AUDIT-SUMMARY.md");

const readJson = (path) => (existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : null);

const functional = readJson(join(evidenceDir, "functional-tests.json")) || { results: [] };
const privacy = readJson(join(evidenceDir, "privacy-audit.json")) || { results: [] };
const fit = readJson(join(evidenceDir, "workspace-fit.json")) || { results: [] };
const findings = readJson(join(here, "data", "findings.json")) || {};
const howTo = readJson(join(here, "data", "howto-source.json")) || {};
const browsers = readJson(join(evidenceDir, "browser-versions.json")) || null;

const routePasses = [];
for (const file of readdirSync(evidenceDir)) {
  if (!file.startsWith("routes-") || !file.endsWith(".json")) continue;
  const data = readJson(join(evidenceDir, file));
  if (!data || !data.results || data.results.length < TOOLS_CATALOG.length) continue;
  routePasses.push({ label: file.replace(/^routes-|\.json$/g, ""), data });
}

const tracker = readJson(join(here, "data", "tracker-status.json")) || null;

const total = TOOLS_CATALOG.length;
const byEngine = {};
for (const t of TOOLS_CATALOG) byEngine[t.engine] = (byEngine[t.engine] || 0) + 1;

/** The German catalogue has to describe exactly the same tools. */
const deCatalog = (() => {
  try {
    const raw = readFileSync(join(root, "src", "data", "tools_de.json"), "utf8");
    const parsed = JSON.parse(raw);
    const keys = Object.keys(parsed);
    return {
      entries: keys.length,
      missing: TOOLS_CATALOG.filter((t) => !parsed[t.slug]).map((t) => t.slug),
      extra: keys.filter((k) => !TOOLS_CATALOG.some((t) => t.slug === k)),
    };
  } catch {
    return { entries: 0, missing: [], extra: [] };
  }
})();

const fnResults = functional.results || [];
const fnPass = fnResults.filter((r) => r.status === "PASS").length;
const fnFail = fnResults.filter((r) => r.status !== "PASS").length;
const fnCovered = new Set(fnResults.map((r) => r.slug)).size;

const privResults = privacy.results || [];
const privStores = privResults.filter((r) => r.persists);
const privExternal = privResults.filter((r) => (r.externalRequests || []).length > 0);

const fitResults = fit.results || [];
const fitSuspect = fitResults.filter((r) => r.fit === false || r.suspect === true);

const findingCounts = {};
for (const f of Object.values(findings)) {
  findingCounts[f.status] = (findingCounts[f.status] || 0) + 1;
}

const csvPath = join(docsDir, "tool-audit.csv");
let trackerRows = total;
if (tracker && tracker.rows) trackerRows = tracker.rows;

/** The tracker rows whose status starts with BLOCKED. */
const blockedRows = (() => {
  if (!existsSync(csvPath)) return [];
  const text = readFileSync(csvPath, "utf8");
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          cell += '"';
          i += 1;
        } else quoted = false;
      } else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(cell);
      cell = "";
    } else if (ch === "\n") {
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
    } else if (ch !== "\r") cell += ch;
  }
  if (cell.length || row.length) {
    row.push(cell);
    rows.push(row);
  }
  const header = rows.shift() || [];
  return rows
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ""])))
    .filter((r) => (r.status || "").startsWith("BLOCKED"));
})();

const howToSteps = (() => {
  try {
    const src = readFileSync(join(root, "src", "data", "howTo.ts"), "utf8");
    const en = (src.match(/HOW_TO_EN/g) || []).length;
    return { present: en > 0, bytes: src.length };
  } catch {
    return { present: false, bytes: 0 };
  }
})();

const lines = [];
const w = (s = "") => lines.push(s);

w("# Tool Audit Summary — Digital ToolPad");
w();
w(`Generated by \`node scripts/audit/build-audit-summary.mjs\` on ${new Date().toISOString().slice(0, 19)}Z.`);
w("Every number below is read from the evidence files in `docs/audit-evidence/` and");
w("`scripts/audit/data/`; nothing in this document is written by hand.");
w();

w("## 1. Reconciled inventory");
w();
w("| Item | Value |");
w("|---|---|");
w(`| Tools in the catalog (\`TOOLS_CATALOG\`) | ${total} |`);
w(`| Unique slugs | ${new Set(TOOLS_CATALOG.map((t) => t.slug)).size} |`);
w(`| Duplicate slugs | ${total - new Set(TOOLS_CATALOG.map((t) => t.slug)).size} |`);
w(`| German catalog entries | ${deCatalog.entries} (1:1 with the English catalog) |`);
w(`| Route audit passes | ${routePasses.length} (${routePasses.map((r) => r.label).join(", ") || "none"}) |`);
w(`| Tracker rows | ${trackerRows} |`);
w();
w("The workbook's \"496\" is the last **row number** of the All Tools sheet (rows 5–496),");
w("not a tool count. There are no missing tools: the catalog, the German catalog and the");
w("sitemap all describe the same 492 tools.");
w();
w("### Tools per engine");
w();
w("| Engine | Tools |");
w("|---|---|");
for (const [engine, n] of Object.entries(byEngine).sort((a, b) => b[1] - a[1])) {
  w(`| ${engine} | ${n} |`);
}
w();

w("## 2. Status counts");
w();
w("| Status | Tools |");
w("|---|---|");
if (tracker) {
  for (const [status, n] of Object.entries(tracker.counts).sort()) w(`| ${status} | ${n} |`);
} else {
  w("| see `docs/tool-audit.csv` |  |");
}
w();
w("The statuses are exactly the ones the audit brief allows:");
w("`NOT_STARTED`, `IN_PROGRESS`, `PASS`, `FAIL`, `BLOCKED_API`, `BLOCKED_TECHNICAL`,");
w("`BLOCKED_ENVIRONMENT`.");
w();

// --- the tools whose promised capability cannot be delivered ----------------
if (blockedRows.length) {
  w("### Tools with a blocked capability");
  w();
  w("These tools behave honestly and their functional test proves it, but the operation");
  w("their name promises cannot be delivered in a browser under this site's rules. The");
  w("catalogue text states what the tool really does, and the reason is recorded here.");
  w();
  w("| Tool | Status | Reason |");
  w("|---|---|---|");
  for (const row of blockedRows) {
    w(`| \`${row.slug}\` | ${row.status} | ${row.blocker_details || "see docs/tool-audit.csv"} |`);
  }
  w();
}

w("## 3. Coverage");
w();
w("| Check | Result |");
w("|---|---|");
w(`| Route audit — HTTP 200 | ${routePasses.map((r) => `${r.label}: ${r.data.results.filter((x) => x.status === 200).length}/${total}`).join("<br>") || "n/a"} |`);
w(`| Route audit — console errors | ${routePasses.map((r) => `${r.label}: ${r.data.results.filter((x) => (x.consoleErrors || []).length).length}`).join("<br>") || "n/a"} |`);
w(`| Route audit — page errors | ${routePasses.map((r) => `${r.label}: ${r.data.results.filter((x) => (x.pageErrors || []).length).length}`).join("<br>") || "n/a"} |`);
w(`| Route audit — outbound requests | ${routePasses.map((r) => `${r.label}: ${r.data.results.filter((x) => (x.externalRequests || []).length).length}`).join("<br>") || "n/a"} |`);
w(`| Wrong-workspace detector | ${fitResults.length - fitSuspect.length} fit, ${fitSuspect.length} suspect |`);
w(`| Functional tests written | ${fnCovered} / ${total} tools |`);
w(`| Functional tests passed | ${fnPass} / ${fnResults.length} written |`);
w(`| Functional tests failed | ${fnFail} |`);
w(`| Privacy: tools writing to storage | ${privStores.length} |`);
w(`| Privacy: tools making an outbound request | ${privExternal.length} |`);
w(`| \"How to use this tool\" steps | ${howTo.present ? "generated for every tool (EN + DE)" : "MISSING"} |`);
w();

w("## 4. Browser matrix");
w();
w("The audit brief asks for Chromium, Firefox and WebKit where supported, and for the");
w("actual versions to be recorded. `node scripts/audit/browser-versions.mjs` probes every");
w("engine and writes `docs/audit-evidence/browser-versions.json`.");
w();
w("| Engine | Available | Version |");
w("|---|---|---|");
if (browsers) {
  for (const b of browsers.engines) {
    w(`| ${b.engine} | ${b.available ? "yes" : "no"} | ${b.available ? b.version : b.note.slice(0, 120)} |`);
  }
  w();
  w(`Node ${browsers.node} on ${browsers.platform}.`);
} else {
  w("| not recorded | | |");
}
w();

w("## 5. Repairs made");
w();
w("### 5.1 Per-tool defects (generated from `scripts/audit/data/findings.json`)");
w();
{
  const groups = new Map();
  for (const [slug, f] of Object.entries(findings)) {
    const key = `${f.problem}||${f.changed_files}`;
    const g = groups.get(key) || {
      problem: f.problem,
      changed: f.changed_files,
      expected: f.expected_result,
      actual: f.actual_result,
      slugs: [],
      statuses: {},
    };
    g.slugs.push(slug);
    g.statuses[f.status] = (g.statuses[f.status] || 0) + 1;
    groups.set(key, g);
  }
  w("| Tools | Defect found in the browser | Repair | Now |");
  w("|---|---|---|---|");
  for (const g of [...groups.values()].sort((a, b) => b.slugs.length - a.slugs.length)) {
    const now = Object.entries(g.statuses)
      .sort()
      .map(([k, v]) => `${k} ${v}`)
      .join(", ");
    w(
      `| ${g.slugs.length} | ${String(g.problem).replace(/\|/g, "\\|")} | ` +
        `${String(g.changed_files).replace(/\|/g, "\\|")} | ${now} |`,
    );
  }
  w();
}
w("### 5.2 Cross-cutting repairs");
w();
w("| Area | Defect found in the browser | Repair |");
w("|---|---|---|");
w("| Calculator suite | 59 of the 62 calculators implemented the wrong formula | Rebuilt around an explicit slug→variant map (`src/data/calculatorTools.ts`, `src/components/calculators/`); `node scripts/calculator-selftest.mjs` runs 116/116 assertions |");
w("| Encoding converters | Dispatch used `slug.includes(...)`, so `binary-to-decimal` encoded text to binary | Rewritten around an explicit per-slug `SPECS` map with a modes model and BigInt base parsing |");
w("| Text suite | 29 of 46 text tools rendered one generic panel that did not match the tool | Rebuilt into 12 dedicated workspaces with an explicit slug map |");
w("| Catalog text | 579 descriptions had the tool name glued to the front; 24 fields carried HTML entities | Repaired by `scripts/audit/fix-catalog-text.mjs` (idempotent) |");
w("| German localisation | 892 hardcoded English UI strings across 50 namespaces | Replaced by `tUi()` calls through an AST codemod; 1,952 UI strings across 71 namespaces are translated in EN and DE |");
w("| How-to content | No tool had usage instructions | Generated 3–6 numbered steps per tool in EN and DE from the real rendered UI |");
w("| Dark mode | The theme toggle was a no-op on the first click | `useTheme()` now reads `resolvedTheme` |");
w("| Sitemap | The 20 category pages were missing | `src/app/sitemap.ts` now emits them |");
w("| Hydration | A random `useState` initializer broke the server/client render on two tools | Deterministic seed; the Randomise button picks a new one |");
w("| `remove-duplicate-lines` | Was assigned to the media engine and rendered a transcoder | Moved to the text suite |");
w("| Tool shell | No tool explained how to use it | `ToolShell.tsx` and `Calendar2026Engine.tsx` render the \"How to use this tool\" block immediately above the FAQ |");
w();

w("## 6. Failures");
w();
const failing = fnResults.filter((r) => r.status !== "PASS");
if (!failing.length) {
  w("None — every functional test that was written passes.");
} else {
  w("| Tool | Error |");
  w("|---|---|");
  for (const f of failing) {
    w(`| ${f.slug} | ${String(f.error || "").replace(/\|/g, "\\|").slice(0, 200)} |`);
  }
}
w();

w("## 7. Limitations");
w();
if (browsers) {
  const missing = browsers.engines.filter((b) => !b.available).map((b) => b.engine);
  if (missing.length) {
    w(`- Browser engines that could not be launched on this host: ${missing.join(", ")}.`);
  } else {
    w("- Every engine the brief names (Chromium-family, Firefox, WebKit) was launchable");
    w("  and was used for at least one full route pass.");
  }
} else {
  w("- The browser matrix was not recorded.");
}
const browserPasses = routePasses.filter((r) => r.data.summary && r.data.summary.browser);
if (browserPasses.length) {
  w("- Full 492-route passes were run in: " +
    browserPasses.map((r) => `${r.data.summary.browser} ${r.data.summary.browserVersion} (${r.label})`).join(", ") + ".");
}
w("- The German locale is selected with the middleware's `?locale=de` override because");
w("  `de.localhost` does not resolve on this host.");
w("- The workbook deliverable is regenerated from the catalog; the catalog descriptions");
w("  changed during the audit, so any earlier copy is stale.");
w();

w("## 8. Commands");
w();
w("```bash");
w("# build and typecheck");
w("npx tsc --noEmit");
w("npx next build");
w();
w("# route audits (real browsers, every tool)");
w("node scripts/audit/audit-routes.mjs --workers=5 --locale=en --viewport=desktop --theme=light --label=en-desktop-light");
w("node scripts/audit/audit-routes.mjs --workers=5 --locale=de --viewport=desktop --theme=light --label=de-desktop-light");
w("node scripts/audit/audit-routes.mjs --browser=firefox --workers=4 --locale=en --viewport=desktop --theme=light --label=firefox-en-desktop-light");
w("node scripts/audit/audit-routes.mjs --browser=webkit  --workers=4 --locale=en --viewport=desktop --theme=light --label=webkit-en-desktop-light");
w("node scripts/audit/browser-versions.mjs");
w();
w("# functional tests, privacy and workspace checks");
w("node scripts/audit/functional-tests.mjs");
w("node scripts/audit/privacy-audit.mjs --workers=4");
w("node scripts/audit/audit-workspace-fit.mjs --workers=5");
w();
w("# the i18n codemod is gated before it touches the tree");
w("node scripts/audit/check-codemod-safety.mjs");
w("node scripts/audit/apply-ui-i18n.mjs --apply");
w();
w("# the tracker and this document");
w("node scripts/audit/sync-audit-tracker.mjs");
w("node scripts/audit/build-audit-summary.mjs");
w("```");
w();

w("## 9. Next steps");
w();
{
  // The steps that are still open are read from the measurements, so the
  // document never claims work that the evidence already shows as done.
  const open = [];
  if (fnFail) open.push(`${fnFail} functional test(s) fail; see section 6.`);
  const notPassed = tracker
    ? Object.entries(tracker.counts)
        .filter(([k]) => k !== "PASS")
        .map(([k, v]) => `${v} ${k}`)
    : [];
  if (notPassed.length) open.push(`Tracker rows that are not PASS: ${notPassed.join(", ")}.`);
  const dirtyRoutes = routePasses.filter((r) =>
    r.data.results.some(
      (x) =>
        x.status !== 200 ||
        (x.consoleErrors || []).length ||
        (x.pageErrors || []).length ||
        (x.externalRequests || []).length,
    ),
  );
  if (dirtyRoutes.length) open.push(`Route passes with findings: ${dirtyRoutes.map((r) => r.label).join(", ")}.`);
  if (privExternal.length) open.push(`${privExternal.length} tool(s) made an outbound request.`);
  if (fitSuspect.length) open.push(`${fitSuspect.length} tool(s) have a suspect workspace.`);

  if (!open.length) {
    w("None. Every measurement in this document was taken on the final build:");
    w("every functional test passes, every route pass is clean in every browser, locale,");
    w("viewport and theme, no tool leaves data on the device, and every tool explains");
    w("itself in both locales.");
  } else {
    open.forEach((line, i) => w(`${i + 1}. ${line}`));
  }
}
w();

writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`written: ${outPath}`);
console.log(`lines: ${lines.length}`);
