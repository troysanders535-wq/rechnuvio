// Generates src/data/engineNamespaces.generated.ts: for every tool engine, the
// `ui.*` message namespaces its component tree reads via useTranslations().
// The tool page ships only those namespaces to the browser instead of the
// whole catalog. Re-run after adding or renaming a useTranslations namespace:
//   node scripts/gen-engine-namespaces.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = path.join(root, "src");
const dispatcherPath = path.join(src, "components/engines/EngineDispatcher.tsx");
const dispatcher = fs.readFileSync(dispatcherPath, "utf8");

const EXTS = [".tsx", ".ts", "/index.tsx", "/index.ts"];
function resolveImport(spec, fromFile) {
  let base;
  if (spec.startsWith("@/")) base = path.join(src, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(fromFile), spec);
  else return null;
  for (const e of ["", ...EXTS]) {
    const p = base + e;
    if (fs.existsSync(p) && fs.statSync(p).isFile()) return p;
  }
  return null;
}

const importRe = /(?:import|export)\s[^;]*?from\s+["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)/g;
const trRe = /useTranslations\(\s*["']([^"']+)["']\s*\)/g;

function collect(entry) {
  const seen = new Set();
  const namespaces = new Set();
  const stack = [entry];
  while (stack.length) {
    const file = stack.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    const text = fs.readFileSync(file, "utf8");
    for (const m of text.matchAll(trRe)) namespaces.add(m[1]);
    for (const m of text.matchAll(importRe)) {
      const resolved = resolveImport(m[1] || m[2], file);
      if (resolved) stack.push(resolved);
    }
  }
  return namespaces;
}

// component name -> file, from the dispatcher's own imports
const componentFile = {};
for (const m of dispatcher.matchAll(/import\s*\{\s*(\w+)\s*\}\s*from\s*["']([^"']+)["']/g)) {
  const resolved = resolveImport(m[2], dispatcherPath);
  if (resolved) componentFile[m[1]] = resolved;
}

const result = {};
for (const m of dispatcher.matchAll(/case\s+"([^"]+)":\s*return\s*<(\w+)/g)) {
  const file = componentFile[m[2]];
  if (!file) throw new Error(`No file for ${m[2]}`);
  result[m[1]] = [...collect(file)].sort();
}
// Special cases and the default branch of the dispatcher.
result.__heads_or_tails = [...collect(componentFile.HeadsOrTailsEngine)].sort();
result.__default = [...collect(componentFile.TextSuiteEngine)].sort();

const out = `// AUTO-GENERATED by scripts/gen-engine-namespaces.mjs - do not edit.
// Message namespaces (under "ui") each tool engine reads on the client.
export const ENGINE_NAMESPACES: Record<string, string[]> = ${JSON.stringify(result, null, 2)};
`;
fs.writeFileSync(path.join(src, "data/engineNamespaces.generated.ts"), out);
console.log(Object.entries(result).map(([k, v]) => `${k}: ${v.length}`).join("\n"));
